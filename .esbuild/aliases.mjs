import fs from "fs";
import path from "path";

const rootDir = process.cwd();
const publicDir = path.join(rootDir, "public");
const esbuildDir = path.join(rootDir, ".esbuild");

// Generated by .esbuild/generate-aliases.js
const aliasesPath = path.join(esbuildDir, "react-aliases.json");

/**
 * Load alias patterns like:
 *   "@moodle/core/*": "public/lib/react/src/*"
 *
 * And convert to a prefix map like:
 *   "@moodle/core/": "<root>/public/lib/react/src"
 */
function loadAliasMap() {
    if (!fs.existsSync(aliasesPath)) {
        return {};
    }

    const raw = JSON.parse(fs.readFileSync(aliasesPath, "utf8"));

    /** @type {Record<string, string>} */
    const map = {};

    for (const [pattern, targetPattern] of Object.entries(raw)) {
        const aliasPrefix = pattern.replace(/\*$/, ""); // "@moodle/core/"
        const targetRootRel = String(targetPattern).replace(/\/\*$/, ""); // "public/lib/react/src"
        map[aliasPrefix] = path.join(rootDir, targetRootRel);
    }

    return map;
}

/**
 * Certain specifiers should never be bundled so we can share the compiled output.
 * These must resolve to browser-loadable ESM files (built outputs).
 */
const staticModuleRemaps = {
    // "react": path.join(publicDir, "lib/react/build/react.js"),
    // "react-dom": path.join(publicDir, "lib/react/build/react.js"),
    // "react-dom/client": path.join(publicDir, "lib/react/build/react-dom-client.js"),
    // "react/jsx-runtime": path.join(publicDir, "lib/react/build/jsx-runtime.js"),
    // "react/jsx-dev-runtime": path.join(publicDir, "lib/react/build/jsx-dev-runtime.js"),
    // "@moodle/core/profiler": path.join(publicDir, "lib/react/build/profiler.js"),
};

function toBrowserPath(value) {
    return value.split(path.sep).join("/");
}

function ensureRelativeSpecifier(specifier) {
    if (specifier.startsWith(".") || specifier.startsWith("/")) {
        return specifier;
    }
    return `./${specifier}`;
}

function getOutputDirForImporter(importer) {
    const marker = `${path.sep}react${path.sep}src${path.sep}`;
    const idx = importer.lastIndexOf(marker);

    if (idx === -1) {
        return path.dirname(importer);
    }

    const before = importer.slice(0, idx);
    const after = importer.slice(idx + marker.length);
    const subDir = path.dirname(after);

    return path.join(before, "react", "build", subDir === "." ? "" : subDir);
}

function buildRelativeRuntimePath(importer, target) {
    if (!importer) {
        const relativeToPublic = path.relative(publicDir, target);
        return ensureRelativeSpecifier(toBrowserPath(relativeToPublic));
    }

    const importerOutputDir = getOutputDirForImporter(importer);
    const relativePath = path.relative(importerOutputDir, target);
    return ensureRelativeSpecifier(toBrowserPath(relativePath));
}

function escapeRegExp(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function createAliasPlugin() {
    const aliasMap = loadAliasMap();

    // Sort by longest prefix first so "@moodle/core_ai/" beats "@moodle/core/"
    const aliasEntries = Object.entries(aliasMap).sort(
        (a, b) => b[0].length - a[0].length
    );

    return {
        name: "moodle-aliases",
        setup(build) {
            // 1) Runtime remaps (external, rewritten to relative browser path)
            Object.entries(staticModuleRemaps).forEach(([specifier, target]) => {
                const filter = new RegExp(`^${escapeRegExp(specifier)}$`);
                build.onResolve({ filter }, (args) => {
                const runtimePath = buildRelativeRuntimePath(args.importer, target);
                return {
                    path: runtimePath,
                    external: true,
                };
                });
            });

            // 2) Component alias resolution (internal, resolved to real files)
            aliasEntries.forEach(([aliasPrefix, targetDir]) => {
                const filter = new RegExp(`^${escapeRegExp(aliasPrefix)}(.*)$`);

                build.onResolve({ filter }, async (args) => {
                    const relPath = args.path.slice(aliasPrefix.length);

                    return await build.resolve(`./${relPath}`, {
                        resolveDir: targetDir,
                        kind: args.kind,
                    });
                });
            });
        },
    };
}
